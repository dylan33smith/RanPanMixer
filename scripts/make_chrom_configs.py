#!/usr/bin/env python
"""Generate `configs/inputs.chrN.yaml` for the 22 autosomes from the chr21 template.

⚠ WHY THIS IS A GENERATOR AND NOT 22 HAND-WRITTEN FILES. Decision C retired the
per-chromosome `chain_span`, which was the only genuinely per-chromosome parameter
the pipeline had. What is left varies formulaically — a chromosome name, two paths,
two checksums — so 22 hand-maintained files would be 22 places for a shared value to
drift out of step, and the drift would be silent.

⚠ CHECKSUMS ARE READ FROM THE `.sha256` SIDECARS ON DISK, never hard-coded here. A
config that states a checksum nobody computed is worse than one that states none.

⚠ The chr21 config is NOT overwritten. It carries the superseded `chain_span` block
and the reasoning behind decision C, and `docs/data.md` registers it as the record of
how the existing chr21 artifacts were built.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
RAW = Path("data/raw")
GFA_URL = ("https://s3-us-west-2.amazonaws.com/human-pangenomics/pangenomes/"
           "freeze/freeze1/pggb/chroms/chr{c}.hprc-v1.0-pggb.gfa.gz")

TEMPLATE = """# Input manifest — chr{c}  (GENERATED by scripts/make_chrom_configs.py)
#
# ⚠ Do not hand-edit. Regenerate. Shared parameters live in this generator so they
# cannot drift between chromosomes; per-chromosome values are paths and checksums.
#
# Under decision C there is NO chain_span: the positions the genetic map does not
# reach are filled from the declared constant rate over gap-free base pairs, and the
# only exclusion left is support == 0, which is a property of the cohort.

chrom: chr{c}

inputs:
  graph:
    path: data/raw/chr{c}.hprc-v1.0-pggb.gfa.gz
    url: {url}
    sha256: {gfa_sha}
    ref_prefix: grch38      # the GRCh38 backbone that gives every record its coordinate
  genetic_map:
    path: external/genetic_maps/chr{c}.b38.gmap
    sha256: {gmap_sha}
    source: >
      SHAPEIT4 b38 maps, extracted from genetic_maps.b38.tar.gz. Verified
      byte-identical to the Beagle redistribution on chr21.

# Decision C (value settled 2026-10-10). ONE global constant for all 22 autosomes.
# A DECLARED CONVENTION, never an estimate of the regions it is applied to: it is used
# precisely where no map speaks, and deCODE assigns 0.0 cM/Mb to chr21's p arm.
declared_rate:
  cM_per_Mb: 1.2707
  gap_table: data/raw/ucsc_gap/gap.txt.gz
  scope: genome
  applies_to: map_silent
  gap_spans: skipped
  derivation: >
    The autosomal mean MAPPED rate, 3,543.8 cM over 2,788.8 Mb, measured across all
    22 autosome maps by scripts/map_coverage.py (logs/B_map_coverage.md).
  note: >
    Gap spans are SKIPPED, settled 2026-10-10. 79.8% of the autosomal map-silent
    sequence is assembly gap, so accumulating through would assert 87.4 cM of the
    109.5 cM total on placeholder base pairs. Safe because no variant of ours falls
    inside any gap, so no position's chain membership changes.
"""


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--outdir", type=Path, default=REPO / "configs")
    ap.add_argument("--chroms", type=int, nargs="+",
                    default=[c for c in range(1, 23) if c != 21])
    a = ap.parse_args(argv)

    missing, written = [], []
    for c in a.chroms:
        gfa = REPO / RAW / f"chr{c}.hprc-v1.0-pggb.gfa.gz"
        gmap = REPO / "external" / "genetic_maps" / f"chr{c}.b38.gmap"
        sha = gfa.with_suffix(gfa.suffix + ".sha256")
        if not gfa.exists():
            missing.append(f"chr{c}: {gfa} not downloaded")
            continue
        if not sha.exists():
            missing.append(f"chr{c}: {sha.name} missing — the GFA has no recorded "
                           f"checksum and is therefore not quotable")
            continue
        if not gmap.exists():
            missing.append(f"chr{c}: {gmap} not extracted")
            continue
        import hashlib
        h = hashlib.sha256()
        with open(gmap, "rb") as fh:
            for blk in iter(lambda: fh.read(1 << 20), b""):
                h.update(blk)
        out = a.outdir / f"inputs.chr{c}.yaml"
        out.write_text(TEMPLATE.format(c=c, url=GFA_URL.format(c=c),
                                       gfa_sha=sha.read_text().strip(),
                                       gmap_sha=h.hexdigest()))
        written.append(out.name)

    for m in missing:
        print(f"SKIP  {m}", file=sys.stderr)
    print(f"wrote {len(written)} config(s); skipped {len(missing)}")
    # ⚠ Assert completeness and fail loudly. A generator that quietly writes 4 of 21
    # configs hands the driver a partial genome that looks like a whole one.
    if missing:
        print(f"\nINCOMPLETE: {len(a.chroms) - len(written)} of {len(a.chroms)} "
              f"chromosomes have no config. Fix the inputs above and re-run; do NOT "
              f"start the driver on a partial set.", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
